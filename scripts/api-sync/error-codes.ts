import type { JsonValue } from "./spec";

/** The committed, generated error-code catalogue (`src/error-codes.ts`), relative to the repo root. */
export const ERROR_CODES_FILE = "src/error-codes.ts";

export type ErrorCodeRetry = "retryable" | "terminal" | "actionable";

export type ErrorCodeRow = {
    code: string;
    status: number;
    retry: ErrorCodeRetry;
    description: string;
};

const RETRY_VALUES: ReadonlySet<string> = new Set(["retryable", "terminal", "actionable"]);
const ROW_RE = /^\|\s*`([A-Z0-9_]+)`\s*\|\s*(\d{3})\s*\|\s*([a-z]+)\s*\|\s*(.*?)\s*\|\s*$/;

/**
 * The rows of the error-code table in the spec's `Errors` tag description
 * (`| \`CODE\` | status | retry | description |`), sorted by code. Throws when the tag or its
 * rows are missing, or a row has a retry class or a duplicate code the SDK doesn't know: a
 * catalogue that silently parses to nothing would pass every check while shipping no codes.
 */
export function parseErrorCodes(spec: JsonValue): ErrorCodeRow[] {
    const tags: JsonValue[] = Array.isArray(spec?.tags) ? spec.tags : [];
    const tag = tags.find((t) => t?.name === "Errors");
    if (!tag || typeof tag.description !== "string") {
        throw new Error('the spec has no "Errors" tag with a description to read error codes from');
    }
    const rows: ErrorCodeRow[] = [];
    const seen = new Set<string>();
    for (const line of tag.description.split("\n")) {
        if (!line.trim().startsWith("| `")) continue;
        const match = ROW_RE.exec(line.trim());
        if (!match) throw new Error(`unparseable error-code row in the "Errors" tag: ${line}`);
        const [, code, status, retry, description] = match;
        if (!RETRY_VALUES.has(retry)) {
            throw new Error(`error code ${code} has an unknown retry class "${retry}"`);
        }
        if (seen.has(code)) throw new Error(`error code ${code} appears twice`);
        seen.add(code);
        rows.push({ code, status: Number(status), retry: retry as ErrorCodeRetry, description });
    }
    if (rows.length === 0) throw new Error('the "Errors" tag lists no error codes');
    return rows.sort((a, b) => (a.code < b.code ? -1 : 1));
}

/** A description made safe for a one-line JSDoc comment. */
function docText(text: string): string {
    return text.replace(/\*\//g, "* /").replace(/\s+/g, " ").trim();
}

/** The source of `src/error-codes.ts`, already in the repo's Biome format. */
export function renderErrorCodes(rows: ErrorCodeRow[]): string {
    const constEntries = rows.flatMap((r) => [
        `    /** ${r.status}, ${r.retry}: ${docText(r.description)} */`,
        `    ${r.code}: "${r.code}",`,
    ]);
    const infoEntries = rows.map(
        (r) => `    ["${r.code}", { status: ${r.status}, retry: "${r.retry}" }],`
    );
    return [
        "// Generated by scripts/api-sync/error-codes.ts from the spec's `Errors` tag. Do not edit:",
        "// `bun scripts/api-sync/index.ts --apply` rewrites it, and `--check` fails when it is stale.",
        "",
        "/**",
        " * How to react to an error code, from the API's error catalogue:",
        " * - `retryable`: the same request can be sent again as is.",
        " * - `terminal`: don't retry.",
        " * - `actionable`: it succeeds only after you fix something (fund a balance, correct details).",
        " * - `unknown`: no code, or a code newer than this SDK.",
        " *",
        " * This is advice for your own handling; the SDK's automatic retries follow `retryable`.",
        " */",
        'export type RetryClass = "retryable" | "terminal" | "actionable" | "unknown";',
        "",
        "/** A catalogued error code's typical HTTP status and retry class. */",
        "export type ErrorCodeInfo = {",
        "    /** The HTTP status the code typically comes with (the endpoint's own docs list the exact one). */",
        "    readonly status: number;",
        '    readonly retry: Exclude<RetryClass, "unknown">;',
        "};",
        "",
        "/**",
        " * Every error code in the API's catalogue, e.g. `ErrorCode.QUOTES_EXPIRED`. Compare it with",
        " * `error.code`; codes newer than this SDK still arrive as plain strings.",
        " */",
        "export const ErrorCode = {",
        ...constEntries,
        "} as const;",
        "",
        "/** A catalogued error code, or any other string (codes the API adds after this SDK). */",
        "export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode] | (string & {});",
        "",
        "const ERROR_CODE_INFO: ReadonlyMap<string, ErrorCodeInfo> = new Map<string, ErrorCodeInfo>([",
        ...infoEntries,
        "]);",
        "",
        "/** The status and retry class of a catalogued `code`; `undefined` for any other value. */",
        "export function errorCodeInfo(code: string | null | undefined): ErrorCodeInfo | undefined {",
        '    return typeof code === "string" ? ERROR_CODE_INFO.get(code) : undefined;',
        "}",
        "",
        "/** The retry class of `code`: `unknown` when there is no code or the catalogue doesn't list it. */",
        "export function retryClassOf(code: string | null | undefined): RetryClass {",
        '    return errorCodeInfo(code)?.retry ?? "unknown";',
        "}",
        "",
    ].join("\n");
}

/** Each code's status and retry in a rendered catalogue, for diffing two versions. */
export function renderedCodes(source: string): Map<string, string> {
    const info = new Map<string, string>();
    for (const m of source.matchAll(
        /^ {4}\["([A-Z0-9_]+)", (\{ status: \d+, retry: "[a-z]+" \})\],$/gm
    )) {
        info.set(m[1], m[2]);
    }
    return info;
}

export type CatalogueDiff = { added: string[]; removed: string[]; changed: string[] };

/** What regenerating changes, by code: new codes, dropped codes, and new status/retry. */
export function diffCatalogue(before: string, after: string): CatalogueDiff {
    const a = renderedCodes(before);
    const b = renderedCodes(after);
    return {
        added: [...b.keys()].filter((c) => !a.has(c)).sort(),
        removed: [...a.keys()].filter((c) => !b.has(c)).sort(),
        changed: [...b.keys()].filter((c) => a.has(c) && a.get(c) !== b.get(c)).sort(),
    };
}
